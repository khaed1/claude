// Builds the differential-test harness: copies the PLEA contracts' text functions VERBATIM into
// small contracts (no edits to their bodies), adds thin external entry points and stubs for the
// chain-state calls the Letterbox makes after the text checks, and writes a Foundry project.
//
//   node harness.mjs <contracts-src-dir> <work-dir>
//
// The copied pieces are re-extracted from the contract sources on every run, so the harness
// always tests what the contracts say today. Each copied block is preceded by a
// "// verbatim: <file> <name>" line; nothing between that line and the next marker is changed.
import fs from 'node:fs';
import path from 'node:path';

// Skips strings and comments so braces inside them do not count.
function matchBrace(src, open) {
  let depth = 0;
  for (let i = open; i < src.length; i++) {
    const c = src[i];
    if (c === '/' && src[i + 1] === '/') { i = src.indexOf('\n', i); if (i < 0) break; continue; }
    if (c === '/' && src[i + 1] === '*') { i = src.indexOf('*/', i + 2) + 1; continue; }
    if (c === '"' || c === "'") {
      for (i++; i < src.length && src[i] !== c; i++) if (src[i] === '\\') i++;
      continue;
    }
    if (c === '{') depth++;
    else if (c === '}') { depth--; if (depth === 0) return i; }
  }
  throw new Error('unbalanced braces');
}

function one(re, src, what) {
  const all = [...src.matchAll(re)];
  if (all.length !== 1) throw new Error(what + ': expected exactly one match, found ' + all.length);
  return all[0];
}

/* A whole function (from the start of its line to its closing brace), with its natspec. */
export function fn(src, file, name) {
  const re = name === 'fallback'
    ? /^[ \t]*fallback\(\)/gm
    : new RegExp('^[ \\t]*function ' + name + '\\(', 'gm');
  const m = one(re, src, file + ' ' + name);
  let start = m.index;
  // natspec / comment lines directly above
  const before = src.slice(0, start).split('\n');
  before.pop();
  let k = before.length;
  while (k > 0 && /^\s*\/\/\//.test(before[k - 1])) k--;
  const docStart = before.slice(0, k).join('\n').length + (k > 0 ? 1 : 0);
  const open = src.indexOf('{', m.index);
  const close = matchBrace(src, open);
  const text = src.slice(docStart, close + 1);
  if (!src.includes(text)) throw new Error('not verbatim');
  return '    // verbatim: ' + file + ' ' + name + '\n' + text.replace(/^\n/, '') + '\n';
}

/* A single declaration line, e.g. a constant, an error or a mapping. */
export function line(src, file, re) {
  const m = one(new RegExp('^[ \\t]*' + re + '.*$', 'gm'), src, file + ' ' + re);
  return '    // verbatim: ' + file + ' line\n' + m[0] + '\n';
}

export function build(srcDir, workDir) {
  const read = (f) => fs.readFileSync(path.join(srcDir, f), 'utf8');
  const gate = read('CabalGate.sol');
  const trib = read('Tribunal.sol');
  const lb = read('Letterbox.sol');
  const pragmaOf = (s) => one(/^pragma solidity [^;]+;/gm, s, 'pragma')[0];
  const pragma = pragmaOf(gate);
  if (pragmaOf(trib) !== pragma || pragmaOf(lb) !== pragma) throw new Error('pragmas differ');
  const solc = pragma.match(/(\d+\.\d+\.\d+)/)[1];

  const G = (n) => fn(gate, 'CabalGate.sol', n);
  const T = (n) => fn(trib, 'Tribunal.sol', n);
  const L = (n) => fn(lb, 'Letterbox.sol', n);
  const GL = (re) => line(gate, 'CabalGate.sol', re);
  const TL = (re) => line(trib, 'Tribunal.sol', re);
  const LL = (re) => line(lb, 'Letterbox.sol', re);

  const sol = `// SPDX-License-Identifier: MIT
${pragma}

// GENERATED by plea/site-design/tools/difftest/harness.mjs from ${srcDir}
// Do not edit: every block after a "verbatim" line is copied byte for byte from the contracts.
// Only the "harness" parts (entry points, stubs for chain state) are written here.

contract GateText {
${GL('error BadPleaText\\(\\);')}
${GL('uint256 public constant MAX_PLEA_BYTES')}
    // harness: the external entry point
    function validate(string calldata text) external pure {
        _validateText(text);
    }

${G('_validateText')}
${G('_refused')}
${G('_at')}
${G('_checkMarker')}
}

contract TribunalText {
${TL('error BadObjectionText\\(\\);')}
${TL('uint256 public constant MAX_TEXT_BYTES')}
    // harness: the external entry point
    function validate(string calldata text) external pure {
        _validateText(text);
    }

${T('_validateText')}
${T('_refused')}
${T('_at')}
${T('_checkMarker')}
${T('_word')}
}

contract LetterboxText {
${LL('error NotOpen\\(')}
${LL('error NothingToAppeal\\(')}
${LL('error BadName\\(')}
${LL('error NameTaken\\(')}
${LL('error LetterTooLong\\(')}
${LL('event NameSet\\(')}
${LL('uint256 internal constant MAX_PLEA_BYTES')}
${LL('uint8 internal constant BY_LETTER')}
${LL('uint8 internal constant AUTO_SELL')}
${LL('mapping\\(address => uint256\\) internal _openOf;')}
${LL('mapping\\(address => string\\) internal _names;')}
${LL('mapping\\(bytes32 => address\\) public nameOwner;')}
    // harness: what a letter did, after the Letterbox's own text checks and the gate's.
    // kind 0 = plea, 1 = appeal; text = the text handed to the gate; gateError = its revert data
    // (empty when the gate accepted the text).
    error Read(uint8 kind, bytes text, bytes gateError);

    GateText internal immutable gate;

    constructor(GateText g) {
        gate = g;
    }

    // harness: ReentrancyGuardTransient's modifier does not touch the text
    modifier nonReentrant() {
        _;
    }

${L('fallback')}
${L('letter')}
${L('_read')}
${L('setName')}
${L('nameOf')}
${L('_setName')}
${L('_checkName')}
${L('_checkLength')}
${L('_after')}
${L('_isWord')}
    // ---------------------------------------------------------------- harness stubs
    // The real _appealTarget / _appeal / _plead / _deliver read chain state (balances, prices, the
    // gate). What they do with the text is: Letterbox._checkLength, then the gate's _validateText
    // (CabalGate.submitFor / appealFor). The stubs do exactly that, then report.
    function _appealTarget(address) internal pure returns (uint256) {
        return 1; // a denied plea to appeal exists
    }

    function _appeal(address, uint256 originalId, string memory text, uint8) internal returns (uint256) {
        if (originalId == 0) revert NothingToAppeal();
        _checkLength(text);
        _gate(1, text);
    }

    function _plead(address, uint256, string memory text, uint8) internal returns (uint256) {
        _checkLength(text);
        _gate(0, text);
    }

    function _deliver(uint256, address) internal pure returns (uint256) {
        revert Read(2, "", "");
    }

    function _gate(uint8 kind, string memory text) internal view {
        try gate.validate(text) {
            revert Read(kind, bytes(text), "");
        } catch (bytes memory err) {
            revert Read(kind, bytes(text), err);
        }
    }
}

// harness: one call per input; reports success (with the display name set, if any) or the revert data.
contract Prober {
    GateText public immutable gate;
    TribunalText public immutable tribunal;
    LetterboxText public immutable letterbox;

    constructor() {
        gate = new GateText();
        tribunal = new TribunalText();
        letterbox = new LetterboxText(gate);
    }

    function gateText(bytes calldata d) external view returns (bool ok, bytes memory data) {
        try gate.validate(string(d)) {
            return (true, "");
        } catch (bytes memory e) {
            return (false, e);
        }
    }

    function objectionText(bytes calldata d) external view returns (bool ok, bytes memory data) {
        try tribunal.validate(string(d)) {
            return (true, "");
        } catch (bytes memory e) {
            return (false, e);
        }
    }

    /// A letter typed into letter(text).
    function letterText(bytes calldata d) external returns (bool ok, bytes memory data) {
        try letterbox.letter(string(d)) {
            return (true, bytes(letterbox.nameOf(address(this))));
        } catch (bytes memory e) {
            return (false, e);
        }
    }

    /// A raw letter: \`d\` is the transaction's input data (the fallback).
    function letterRaw(bytes calldata d) external returns (bool ok, bytes memory data) {
        (bool s, bytes memory r) = address(letterbox).call(d);
        if (s) return (true, bytes(letterbox.nameOf(address(this))));
        return (false, r);
    }

    function name(bytes calldata d) external returns (bool ok, bytes memory data) {
        try letterbox.setName(string(d)) {
            return (true, bytes(letterbox.nameOf(address(this))));
        } catch (bytes memory e) {
            return (false, e);
        }
    }
}
`;
  fs.mkdirSync(path.join(workDir, 'src'), { recursive: true });
  fs.writeFileSync(path.join(workDir, 'src', 'Harness.sol'), sol);
  // The contracts' own compiler settings (khaed1/plea foundry.toml).
  fs.writeFileSync(path.join(workDir, 'foundry.toml'), `[profile.default]
src = "src"
out = "out"
libs = []
solc = "${solc}"
evm_version = "cancun"
optimizer = true
optimizer_runs = 200
via_ir = true
bytecode_hash = "none"
cbor_metadata = false
`);
  return { file: path.join(workDir, 'src', 'Harness.sol'), solc };
}

if (import.meta.url === 'file://' + process.argv[1]) {
  const [srcDir, workDir] = process.argv.slice(2);
  if (!srcDir || !workDir) { console.error('usage: node harness.mjs <contracts-src-dir> <work-dir>'); process.exit(2); }
  console.log(build(srcDir, workDir).file);
}
