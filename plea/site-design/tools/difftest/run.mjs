#!/usr/bin/env node
// Differential test: text-check.js against the PLEA contracts' own Solidity, run on a local EVM.
//
//   node plea/site-design/tools/difftest/run.mjs [--src <khaed1/plea/src>] [--work <dir>]
//        [--seed 1] [--scale 1] [--js <text-check.js>] [--no-scan] [--save]
//
//   --src    the contracts (default $PLEA_SRC or /home/user/khaed1/plea/src); read only
//   --work   the Foundry project, build output and mismatches.json (default $TMPDIR/plea-difftest)
//   --scale  multiplies the number of generated inputs (1 = about 75,000 plus the scans)
//   --save   refresh the verified copy of the harness next to this script (Harness.sol)
//
// Needs Foundry (forge, anvil, cast) on PATH or in ~/.foundry/bin. It
//   1. copies CabalGate's, Tribunal's and the Letterbox's text functions verbatim into a harness
//      (harness.mjs) and compiles it with the contracts' compiler settings,
//   2. deploys it on a throwaway anvil and runs every generated input (gen.mjs) through both the
//      Solidity (eth_call) and text-check.js, comparing accept/refuse, the error, and for letters
//      what the letter is read as and the text the gate gets,
//   3. scans every Unicode code point through the gate and the Tribunal (and, where text-check.js
//      accepts bytes, every 1- and 2-byte sequence),
//   4. checks the real Letterbox's function selectors cannot start a letter text-check.js accepts,
//   5. checks the position the message gives for texts with one planted defect.
// Exit code 0 when nothing differs. Mismatches are written to <work>/mismatches.json.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawn, execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { build, fn } from './harness.mjs';
import { generate, refusedRangesFromSource } from './gen.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const args = Object.fromEntries(process.argv.slice(2).reduce((acc, a, k, all) => {
  if (a.startsWith('--')) acc.push([a.slice(2), all[k + 1] && !all[k + 1].startsWith('--') ? all[k + 1] : true]);
  return acc;
}, []));
const SRC = path.resolve(args.src || process.env.PLEA_SRC || '/home/user/khaed1/plea/src');
const WORK = path.resolve(args.work || path.join(os.tmpdir(), 'plea-difftest'));
const SEED = Number(args.seed || 1);
const SCALE = Number(args.scale || 1);
const JS = path.resolve(args.js || path.join(here, '..', '..', 'text-check.js'));
const FOUNDRY = path.join(os.homedir(), '.foundry', 'bin');
const env = { ...process.env, PATH: FOUNDRY + path.delimiter + process.env.PATH };

const T = createRequire(import.meta.url)(JS);
const enc = new TextEncoder();
const hex = (u8) => Buffer.from(u8).toString('hex');
const toBytes = (x) => (typeof x === 'string' ? enc.encode(x) : x);
const show = (x) => (typeof x === 'string' ? JSON.stringify(x) : '0x' + hex(x));

// ------------------------------------------------------------------ build + chain
const t0 = Date.now();
build(SRC, WORK);
// The copy saved next to this script is the harness last verified; say so when the contracts moved on.
const saved = path.join(here, 'Harness.sol');
const strip = (f) => (fs.existsSync(f) ? fs.readFileSync(f, 'utf8').replace(/^\/\/ GENERATED by .*$/m, '') : '');
const fresh = path.join(WORK, 'src', 'Harness.sol');
if (args.save) fs.copyFileSync(fresh, saved);
else if (strip(saved) !== strip(fresh)) console.log('note: the contracts changed since tools/difftest/Harness.sol was saved (diff it; --save updates it)');
execFileSync('forge', ['build', '--quiet'], { cwd: WORK, env, stdio: ['ignore', 'inherit', 'inherit'] });
const art = (name) => JSON.parse(fs.readFileSync(path.join(WORK, 'out', 'Harness.sol', name + '.json'), 'utf8'));
const prober = art('Prober');
const lbIds = Object.values(art('LetterboxText').methodIdentifiers);
const sel = (sig) => execFileSync('cast', ['sig', sig], { env }).toString().trim().slice(2);
const ERR = {};
for (const s of ['BadPleaText()', 'BadObjectionText()', 'BadName()', 'NameTaken()', 'LetterTooLong(uint256,uint256)', 'NotOpen(uint256)',
  'NothingToAppeal()', 'Read(uint8,bytes,bytes)', 'Error(string)', 'Panic(uint256)']) ERR[sel(s)] = s.slice(0, s.indexOf('('));

const port = 20000 + Math.floor(Math.random() * 20000);
const anvil = spawn('anvil', ['--port', String(port), '--silent', '--disable-code-size-limit', '--gas-limit', '1000000000'], { env, stdio: 'ignore' });
process.on('exit', () => anvil.kill());
const URL_ = 'http://127.0.0.1:' + port;
let rpcId = 0;
async function rpc(method, params) {
  const r = await fetch(URL_, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ jsonrpc: '2.0', id: ++rpcId, method, params }) });
  const j = await r.json();
  if (j.error) throw new Error(method + ': ' + JSON.stringify(j.error));
  return j.result;
}
async function rpcBatch(calls) {
  const body = calls.map((c, k) => ({ jsonrpc: '2.0', id: k, method: c[0], params: c[1] }));
  const r = await fetch(URL_, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify(body) });
  const j = await r.json();
  const out = new Array(calls.length);
  for (const x of j) out[x.id] = x;
  return out;
}
for (let k = 0; ; k++) {
  try { await rpc('eth_chainId', []); break; } catch (e) { if (k > 100) throw e; await new Promise((res) => setTimeout(res, 100)); }
}
const [from] = await rpc('eth_accounts', []);
const txh = await rpc('eth_sendTransaction', [{ from, data: '0x' + prober.bytecode.object.replace(/^0x/, ''), gas: '0x1c9c380' }]);
let receipt = null;
for (let k = 0; !receipt && k < 100; k++) {
  receipt = await rpc('eth_getTransactionReceipt', [txh]);
  if (!receipt) await new Promise((res) => setTimeout(res, 100));
}
if (!receipt || receipt.status !== '0x1') throw new Error('harness deployment failed: ' + JSON.stringify(receipt));
const PROBER = receipt.contractAddress;
const FN = {};
for (const [sig, id] of Object.entries(prober.methodIdentifiers)) FN[sig.slice(0, sig.indexOf('('))] = id;
const SUITE_FN = { gate: 'gateText', objection: 'objectionText', letter: 'letterText', 'letter-raw': 'letterRaw', name: 'name' };

// ------------------------------------------------------------------ ABI
const word = (n) => n.toString(16).padStart(64, '0');
function callData(fnName, b) {
  const pad = (32 - (b.length % 32)) % 32;
  return '0x' + FN[fnName] + word(32) + word(b.length) + hex(b) + '00'.repeat(pad);
}
const rd = (h, at) => parseInt(h.slice(at * 2, at * 2 + 64), 16);
function bytesAt(h, off) {
  const n = rd(h, off);
  return Uint8Array.from(Buffer.from(h.slice((off + 32) * 2, (off + 32 + n) * 2), 'hex'));
}
/* (bool ok, bytes data) */
function decodeProbe(result) {
  const h = result.slice(2);
  return { ok: rd(h, 0) === 1, data: bytesAt(h, rd(h, 32)) };
}
function errOf(data) {
  if (data.length === 0) return { name: 'empty revert' };
  const s = hex(data.subarray(0, 4));
  const name = ERR[s] || '0x' + s;
  const h = hex(data.subarray(4));
  if (name === 'LetterTooLong') return { name, text: 'LetterTooLong(' + rd(h, 0) + ', ' + rd(h, 32) + ')' };
  if (name === 'NotOpen') return { name, id: rd(h, 0) };
  if (name === 'Read') return { name, kind: rd(h, 0), text: bytesAt(h, rd(h, 32)), gateError: bytesAt(h, rd(h, 64)) };
  return { name };
}

/* What the contract did, in the terms text-check.js uses. */
function contractOutcome(suite, p) {
  if (suite === 'gate' || suite === 'objection' || suite === 'name') {
    if (p.ok) return { ok: true };
    return { ok: false, error: errOf(p.data).name };
  }
  if (p.ok) return p.data.length ? { kind: 'name', ok: true, body: p.data } : { kind: 'clear-name', ok: true };
  const e = errOf(p.data);
  if (e.name === 'Read') {
    const kind = ['plea', 'appeal', 'sell'][e.kind];
    if (e.gateError.length === 0) return { kind, ok: true, body: e.text };
    return { kind, ok: false, body: e.text, error: errOf(e.gateError).name };
  }
  if (e.name === 'NotOpen') return { kind: 'sell', ok: true };
  if (e.name === 'BadName') return { kind: 'name', ok: false, error: 'BadName' };
  if (e.name === 'LetterTooLong') return { kind: 'plea|appeal', ok: false, error: e.text };
  return { kind: '?', ok: false, error: e.name };
}

const eqBytes = (a, b) => a.length === b.length && a.every((x, k) => x === b[k]);
function jsOutcome(suite, input) {
  if (suite === 'gate') return T.checkText(input);
  if (suite === 'objection') return T.checkObjection(input);
  if (suite === 'name') return T.checkName(input);
  return T.checkLetter(input);
}
function differ(suite, c, j) {
  const why = [];
  if (c.ok !== j.ok) why.push('ok: contract ' + c.ok + ', js ' + j.ok);
  if (!c.ok && !j.ok && c.error !== j.error) why.push('error: contract ' + c.error + ', js ' + j.error);
  if (suite === 'letter' || suite === 'letter-raw') {
    if (c.kind === 'plea|appeal' ? !['plea', 'appeal'].includes(j.kind) : c.kind !== j.kind) why.push('kind: contract ' + c.kind + ', js ' + j.kind);
    if (c.body && j.body !== undefined && !eqBytes(c.body, toBytes(j.body))) why.push('text: contract 0x' + hex(c.body) + ', js 0x' + hex(toBytes(j.body)));
  }
  return why;
}

// ------------------------------------------------------------------ run
const mismatches = [];
const counts = {};
let ran = 0;
let skipped = 0;
async function runAll(cases) {
  const B = 400;
  const batches = [];
  for (let k = 0; k < cases.length; k += B) batches.push(cases.slice(k, k + B));
  let next = 0;
  async function worker() {
    while (next < batches.length) {
      const batch = batches[next++];
      const res = await rpcBatch(batch.map((c) => ['eth_call', [{ to: PROBER, data: callData(SUITE_FN[c.suite], toBytes(c.input)), gas: '0x3b9aca00' }, 'latest']]));
      batch.forEach((c, k) => {
        if (res[k].error) throw new Error('eth_call failed for ' + show(c.input) + ': ' + JSON.stringify(res[k].error));
        c.contract = contractOutcome(c.suite, decodeProbe(res[k].result));
      });
    }
  }
  await Promise.all([worker(), worker(), worker(), worker()]);
  for (const c of cases) {
    const j = jsOutcome(c.suite, c.input);
    c.js = j;
    ran++;
    counts[c.suite] = (counts[c.suite] || 0) + 1;
    const why = differ(c.suite, c.contract, j);
    if (why.length) mismatches.push({ suite: c.suite, note: c.note, input: show(c.input), bytes: '0x' + hex(toBytes(c.input)), why, contract: { ...c.contract, body: c.contract.body && show(c.contract.body) }, js: { kind: j.kind, ok: j.ok, error: j.error, issues: j.issues && j.issues.map((i) => i.message) } });
  }
}

const jsBytes = (() => { try { return T.checkText(Uint8Array.of(0x61)).bytes === 1; } catch { return false; } })();
const refused = refusedRangesFromSource(fn(fs.readFileSync(path.join(SRC, 'CabalGate.sol'), 'utf8'), 'CabalGate.sol', '_refused'));
let cases = generate({ seed: SEED, scale: SCALE, refused, bytes: jsBytes });
cases = cases.filter((c) => {
  if (c.suite !== 'letter-raw') return true;
  const b = toBytes(c.input);
  if (b.length >= 4 && lbIds.includes(hex(b.subarray(0, 4)))) { skipped++; return false; }
  return true;
});
await runAll(cases);

// every code point (and every 1- and 2-byte sequence where JS takes bytes) through the gate and the Tribunal
const generated = { ran, counts: { ...counts } };
let scanned = 0;
if (!args['no-scan']) {
  for (const suite of ['gate', 'objection']) {
    const groups = [];
    let cur = [];
    let curBytes = 0;
    for (let c = 0; c <= 0x10ffff; c++) {
      if (c >= 0xd800 && c <= 0xdfff) continue;
      const w = c < 0x80 ? 1 : c < 0x800 ? 2 : c < 0x10000 ? 3 : 4;
      if (curBytes + w > 280) { groups.push(cur); cur = []; curBytes = 0; }
      cur.push(c);
      curBytes += w;
    }
    groups.push(cur);
    const gcases = groups.map((g) => ({ suite, note: 'scan group', input: String.fromCodePoint(...g), group: g }));
    const before = mismatches.length;
    await runAll(gcases);
    mismatches.length = before; // a group only tells us where to look
    const singles = [];
    for (const g of gcases) {
      if (g.contract.ok && g.js.ok) continue;
      for (const c of g.group) singles.push({ suite, note: 'scan U+' + c.toString(16), input: String.fromCodePoint(c) });
    }
    await runAll(singles);
    scanned += gcases.length + singles.length;
    if (jsBytes) {
      const raw = [];
      for (let a = 0; a < 256; a++) for (let b = 0; b < 256; b++) raw.push({ suite, note: 'scan 2 bytes', input: Uint8Array.of(a, b) });
      await runAll(raw);
      scanned += raw.length;
    }
  }
}

// the real Letterbox's selectors: a raw letter starting with one goes to that function instead
const lbSrc = fs.readFileSync(path.join(SRC, 'Letterbox.sol'), 'utf8');
const contractBody = lbSrc.slice(lbSrc.indexOf('contract Letterbox'));
const sigs = [];
for (const m of contractBody.matchAll(/function (\w+)\(([^)]*)\)\s+(?:external|public)/g)) {
  const types = m[2].split(',').map((p) => p.trim().split(/\s+/)[0]).filter(Boolean).map((t) => (t === 'uint' ? 'uint256' : t));
  sigs.push(m[1] + '(' + types.join(',') + ')');
}
for (const m of contractBody.matchAll(/mapping\((\w+) => \w+\) public (\w+);/g)) sigs.push(m[2] + '(' + m[1] + ')');
const selectorFails = [];
for (const s of sigs) {
  const b = Buffer.from(sel(s), 'hex');
  for (const tail of [[], [0x61], [0x80, 0x61], [0x80, 0x80, 0x61], [0x80, 0x80, 0x80, 0x61]]) {
    const letterBytes = Uint8Array.from([...b, ...tail]);
    let ok;
    if (jsBytes) ok = T.checkLetter(letterBytes).ok;
    else { try { ok = T.checkLetter(new TextDecoder('utf-8', { fatal: true, ignoreBOM: true }).decode(letterBytes)).ok; } catch { ok = false; } }
    if (ok) selectorFails.push(s + ' = 0x' + b.toString('hex') + ' + 0x' + hex(Uint8Array.from(tail)));
  }
}

// positions in the messages, for texts with one planted defect
const seg = typeof Intl !== 'undefined' && Intl.Segmenter ? new Intl.Segmenter('en', { granularity: 'grapheme' }) : null;
function charNumber(s, index) {
  if (!seg) return [...s.slice(0, index)].length + 1;
  let k = 0;
  for (const g of seg.segment(s)) { k++; if (index < g.index + g.segment.length) return k; }
  return k + 1;
}
const positionFails = [];
let positions = 0;
for (const c of cases) {
  if (!c.plant || typeof c.input !== 'string' || c.js.ok) continue;
  const first = c.js.issues.find((i) => !i.warning && i.at !== undefined);
  if (!first) continue;
  positions++;
  const want = { index: c.plant.index, at: charNumber(c.input, c.plant.index) };
  const got = { index: first.index, at: first.at };
  const okIndex = first.index === undefined || first.index === want.index;
  if (!okIndex || got.at !== want.at) positionFails.push({ input: show(c.input), note: c.note, want, got, message: first.message });
}

// ------------------------------------------------------------------ report
fs.mkdirSync(WORK, { recursive: true });
fs.writeFileSync(path.join(WORK, 'mismatches.json'), JSON.stringify({ mismatches, selectorFails, positionFails }, null, 1));
const bySuite = {};
for (const m of mismatches) bySuite[m.suite] = (bySuite[m.suite] || 0) + 1;
console.log('text-check.js: ' + JS + (jsBytes ? ' (accepts raw bytes)' : ' (strings only: raw-byte cases not run)'));
console.log('contracts:     ' + SRC + '   harness: ' + path.join(WORK, 'src', 'Harness.sol'));
console.log('inputs run:    ' + generated.ran + ' generated (' + Object.entries(generated.counts).map(([k, v]) => k + ' ' + v).join(', ') + '; seed ' + SEED + ')');
if (scanned) console.log('               + ' + scanned + ' scan inputs (every code point through the gate and the Tribunal, in groups, then one by one where either side refuses' + (jsBytes ? '; every 2-byte sequence' : '') + ')');
const split = {};
for (const c of cases) { const k = c.suite; split[k] = split[k] || [0, 0]; split[k][c.contract.ok ? 0 : 1]++; }
console.log('contract said: ' + Object.entries(split).map(([k, [a, r]]) => k + ' ' + a + ' accepted / ' + r + ' refused').join(', '));
if (skipped) console.log('               ' + skipped + ' raw letters skipped: they start with a harness function selector');
console.log('mismatches:    ' + mismatches.length + (mismatches.length ? ' (' + Object.entries(bySuite).map(([k, v]) => k + ' ' + v).join(', ') + ')' : ''));
const seen = new Set();
for (const m of mismatches) {
  const key = m.suite + '|' + m.why.map((w) => w.replace(/0x[0-9a-f]+/g, '')).join(';') + '|' + m.note.replace(/[0-9a-f]+$/, '');
  if (seen.has(key)) continue;
  seen.add(key);
  console.log('  - ' + m.suite + ' [' + m.note + '] ' + m.input.slice(0, 120) + '\n      ' + m.why.join('; '));
  if (seen.size > 40) { console.log('  ...'); break; }
}
console.log('selectors:     ' + sigs.length + ' Letterbox functions checked, ' + selectorFails.length + ' could start an accepted letter' + (selectorFails.length ? ': ' + selectorFails.join(', ') : ''));
console.log('positions:     ' + positions + ' planted defects checked, ' + positionFails.length + ' wrong');
for (const p of positionFails.slice(0, 12)) console.log('  - ' + p.input.slice(0, 100) + '  want ' + JSON.stringify(p.want) + ' got ' + JSON.stringify(p.got) + '\n      ' + p.message);
console.log('time:          ' + ((Date.now() - t0) / 1000).toFixed(1) + ' s; details: ' + path.join(WORK, 'mismatches.json'));
anvil.kill();
process.exit(mismatches.length || selectorFails.length || positionFails.length ? 1 : 0);
