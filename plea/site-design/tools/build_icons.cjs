// Builds icons.js: an inline SVG sprite of Phosphor Bold icons (MIT, phosphoricons.com).
// node tools/build_icons.cjs <path to @phosphor-icons/core>
const fs = require('fs');
const path = require('path');
const core = process.argv[2];
const names = ['check', 'x', 'clock', 'hourglass', 'envelope-simple', 'copy', 'arrow-square-out', 'sun', 'moon', 'list',
  'warning', 'arrow-down', 'wallet', 'gavel', 'scales', 'prohibit', 'share-network', 'info', 'caret-down', 'trophy',
  'x-logo', 'seal-check', 'arrow-right', 'megaphone-simple', 'hand-palm', 'armchair', 'fire', 'coins', 'timer',
  'user-circle', 'arrow-clockwise', 'plugs', 'magnifying-glass', 'link', 'question', 'check-circle', 'x-circle',
  'warning-circle', 'minus'];
let symbols = '';
for (const n of names) {
  const svg = fs.readFileSync(path.join(core, 'assets/bold', n + '-bold.svg'), 'utf8');
  const inner = svg.replace(/^.*?<svg[^>]*>/s, '').replace(/<\/svg>\s*$/s, '');
  symbols += `<symbol id="i-${n}" viewBox="0 0 256 256">${inner}</symbol>`;
}
const out = `/* PLEA icons: Phosphor Bold (MIT License, Copyright (c) 2023 Phosphor Icons), as an inline sprite so
   pages work from file:// and IPFS without a fetch. Use: <svg class="icon" aria-hidden="true"><use href="#i-check"/></svg>.
   Generated by tools/build_icons.cjs; ${names.length} icons. */
(function () {
  var sprite = '<svg xmlns="http://www.w3.org/2000/svg" style="display:none" aria-hidden="true">${symbols.replace(/'/g, "\\'")}</svg>';
  function add() { if (!document.getElementById('plea-icons')) { var d = document.createElement('div'); d.id = 'plea-icons'; d.innerHTML = sprite; document.body.insertBefore(d, document.body.firstChild); } }
  if (document.body) add(); else document.addEventListener('DOMContentLoaded', add);
})();
`;
fs.writeFileSync(path.join(__dirname, '..', 'icons.js'), out);
console.log('icons.js', out.length, 'bytes,', names.length, 'icons');
